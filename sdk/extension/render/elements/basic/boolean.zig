/// One frame of editing: Enter toggles `value`, Escape cancels. Returns true
/// when editing ends.
pub fn step(value: *bool) bool { _ = value; return undefined; }

/// Draw `[x]` or `[ ]` right-aligned in the row `(x, y, w, h)`.
pub fn render(x: f32, y: f32, w: f32, h: f32, value: bool, color: i32) void { _ = x; _ = y; _ = w; _ = h; _ = value; _ = color; }
